  // Merge into window.CAREERS_DATA
  if (window.CAREERS_DATA) {
    window.CAREERS_DATA = window.CAREERS_DATA.concat(additionalCareers);
  } else {
    window.CAREERS_DATA = additionalCareers;
  }
